#!/usr/bin/env python3
"""Generate the use case overview: the actor-goal table and a Mermaid use case diagram (usecase-beta,
Mermaid 12.0.0 and later) between two markers of docs/use_cases.md, from the use case files' front
matter. People write everything outside the markers.

Usage:
    use_case_map.py [--docs DIR] [--check [--strict]]

--check writes nothing and reports when the block differs from what the files produce;
with --strict it then exits 1. Exit 0 current, written or reported (an unreadable
file or a refused id or goal included), 1 stale, unreadable or refused with --check
--strict, or when writing is refused (markers out of order, a file it cannot read, a
use case whose id or goal cannot be read because it runs on several lines: writing
would drop the use case or empty its goal), 2 usage, 5 old formats. --check prints
such a refusal as the finding FRONT_MATTER at its line, and judges the rest of the
block as it will read once the value is on one line.
Requires Python 3.9+, standard library only. Writes only docs/use_cases.md.
"""
import argparse
import copy
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import spec_model as model  # noqa: E402

# the release these copies belong to; hook_gate.py refuses siblings of another release
UPSPEC_VERSION = "1.4.0"

START = "<!-- generated by use_case_map.py: edits between these markers are overwritten -->"
END = "<!-- end generated -->"


def label(text):
    """A Mermaid label: '&' first, then quotes, angle brackets and pipes as entities, wrapped in quotes."""
    return '"%s"' % (text.replace("&", "#amp;").replace('"', "#quot;").replace("<", "#lt;").replace(">", "#gt;")
                     .replace("|", "#124;"))


def cell(text):
    """A Markdown table cell: a pipe stays inside its cell."""
    return text.replace("|", "\\|")


def overview_block(use_cases, system, overview_path=None):
    """The generated block. Node ids are positional (actor_1, uc_001), never derived from names, so two
    names that differ only in punctuation stay two nodes and no id can be a Mermaid keyword. Labels use
Mermaid's entity codes, which the use case diagram reads as the flowchart does (checked on 12.0.0)."""
    cases = sorted((uc for uc in use_cases if uc.id), key=lambda uc: uc.id)
    overview_dir = os.path.dirname(os.path.abspath(overview_path)) if overview_path else (
        os.path.dirname(os.path.dirname(os.path.abspath(cases[0].path))) if cases and getattr(cases[0], "path", None) else None
    )
    rows = ["| Actor | Goal | Use case |", "|---|---|---|"]
    for uc in cases:
        if overview_dir and getattr(uc, "path", None):
            rel = os.path.relpath(os.path.abspath(uc.path), overview_dir).replace(os.sep, "/")
        else:
            rel = "use_cases/%s" % os.path.basename(getattr(uc, "path", ""))
        link = "[%s %s](%s)" % (uc.id, cell(uc.name), rel)
        rows.append("| %s | %s | %s |" % (cell(", ".join(uc.primary_actors)), cell(uc.field("Goal")), link))
    actors = {}
    for uc in cases:
        for name in uc.primary_actors + uc.secondary_actors:
            actors.setdefault(name, "actor_%d" % (len(actors) + 1))
    uc_node = {uc.id: "uc_" + uc.id.split("-")[1] for uc in cases}
    chart = ["```mermaid", "usecase-beta", "  direction LR"]
    chart += ["  actor %s(%s)" % (node, label(name)) for name, node in actors.items()]
    chart.append("  systemBoundary system[%s]" % label(system or "System"))
    chart += ["    %s(%s)" % (uc_node[uc.id], label("%s %s" % (uc.id, uc.name))) for uc in cases]
    chart.append("  end")
    # Plain association lines, as in UML; a primary actor is written first and a secondary actor last,
    # which keeps the primary actors on the left of the boundary and the secondary actors on the right.
    for uc in cases:
        chart += ["  %s -- %s" % (actors[a], uc_node[uc.id]) for a in uc.primary_actors]
        chart += ["  %s -- %s" % (uc_node[uc.id], actors[a]) for a in uc.secondary_actors]
    chart.append("```")
    return "\n".join([START, "", *rows, "", *chart, END])


class MarkerOrderError(ValueError):
    """The generated block cannot be located safely."""


def _split(text):
    """(before, block, after); block is None when the markers are missing."""
    if START not in text or END not in text:
        return text, None, ""
    if text.index(END) < text.index(START):
        raise MarkerOrderError("the generated markers are out of order")
    before, rest = text.split(START, 1)
    block, after = rest.split(END, 1)
    return before, START + block + END, after


# The keys of a use case the overview cannot do without: refused as a value on several lines, an id would drop
# the use case from the overview and a goal would leave its cell empty. While one is refused the overview is
# not written, and is not current.
GUARDED_KEYS = ("id", "goal")
# Stands in for a refused goal while the rest of the block is judged; no text of a use case holds it.
UNREAD = "\x00unread\x00"


def refusals(use_cases):
    """[(path, line, key)] for each guarded key refused in a use case's front matter, in file order."""
    return sorted((uc.path, uc.front_matter.refused[key], key)
                  for uc in use_cases for key in GUARDED_KEYS if key in uc.front_matter.refused)


def refusal_lines(use_cases):
    return ["%s:%d: ERROR FRONT_MATTER: the %s cannot be read (it runs on several lines); write it on one line: "
            "until then the overview cannot be generated" % refusal for refusal in refusals(use_cases)]


def _stand_in(uc):
    """The use case as the block would show it once its refused keys are written on one line: the id its file
    name carries, and UNREAD for the goal. Used only to judge the rest of the block, never written."""
    refused = uc.front_matter.refused
    if not any(key in refused for key in GUARDED_KEYS):
        return uc
    meta = dict(uc.front_matter.meta)
    named = model.RE_UC_ID.search(os.path.basename(uc.path))
    if "id" in refused and named:
        meta["id"] = (named.group(0), refused["id"])
    if "goal" in refused:
        meta["goal"] = (UNREAD, refused["goal"])
    judged = copy.copy(uc)
    judged.front_matter = model.FrontMatter(meta, uc.front_matter.body_start, uc.front_matter.problems, refused)
    return judged


def expected(docs, use_cases=None):
    meta = model.read_front_matter(model.read_lines(docs.overview))[0] if docs.overview else {}
    system = model._as_text(meta.get("system", ("", 0))[0])
    overview_path = docs.overview or os.path.join(docs.root, "use_cases.md")
    use_cases = model.load_use_cases(docs) if use_cases is None else use_cases
    return overview_block(use_cases, system, overview_path=overview_path)


def stale_reason(docs, default="run use_case_map.py to regenerate the overview"):
    """None when the block is what the use case files produce; otherwise the finding to show for it. A use case
    whose id or goal is refused is judged as it will read once that value is on one line (its file name's id,
    any goal), so its refusal is its one finding and a stale row elsewhere still shows."""
    if not docs.overview:
        return default
    with open(docs.overview, encoding="utf-8") as handle:
        text = handle.read().replace("\r\n", "\n")
    try:
        block = _split(text)[1]
    except MarkerOrderError as exc:
        return str(exc)
    if block is None:
        return default
    wanted = expected(docs, [_stand_in(uc) for uc in model.load_use_cases(docs)])
    pattern = re.escape(wanted).replace(re.escape(UNREAD), r"[^\n]*?")
    return None if re.fullmatch(pattern, block) else default


def current(docs):
    """The block is what the files produce, and no guarded key is refused (refused, it cannot be generated)."""
    return stale_reason(docs) is None and not refusals(model.load_use_cases(docs))


def write(docs):
    path = docs.overview or os.path.join(docs.root, "use_cases.md")
    text = (open(path, encoding="utf-8").read().replace("\r\n", "\n") if os.path.isfile(path)
            else "---\nsystem: \n---\n# Use cases\n\n## Scope\n\n## Delivery order\n\n")
    before, block, after = _split(text)
    new_block = expected(docs)
    if block == new_block:
        return False
    new = before + new_block + after if block is not None else text.rstrip("\n") + "\n\n" + new_block + "\n"
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(new)
    docs.overview = path
    return True


def main(argv):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--docs", default=None)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--strict", action="store_true", help="with --check: exit 1 when the block is stale or an id or goal is refused")
    args = parser.parse_args(argv)
    docs = model.Docs(args.docs or model.docs_default("."))
    # The check reports an unreadable file as a finding; writing the overview cannot be done without it.
    stop = model.stop_if_old(docs, strict=args.strict if args.check else True)
    if stop is not None:
        return stop
    refused = refusal_lines(model.load_use_cases(docs))
    if args.check:
        reason = stale_reason(docs, default="the generated block differs from the use case files; run use_case_map.py")
        found = refused + (["%s:1: ERROR STALE_OVERVIEW: %s" % (docs.overview or os.path.join(docs.root, "use_cases.md"),
                                                                  reason)] if reason else [])
        for line in found:
            print(line)
        # The findings are the output; only a strict check turns them into a failure.
        return 1 if args.strict and found else 0
    if refused:
        # Writing now would drop a use case from the overview, or empty its goal cell.
        for line in refused:
            print(line + "; the overview was not written", file=sys.stderr)
        return 1
    try:
        write(docs)
    except MarkerOrderError as exc:
        print("%s:1: ERROR STALE_OVERVIEW: %s" % (docs.overview, exc), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
